//! Known-answer tests against frames produced by the REFERENCE Go encoder
//! (github.com/zap-proto/http v0.3.1 `AppendRequest`/`AppendResponse`).
//!
//! These are not hand-written expectations — every byte array below was emitted
//! by the Go implementation and pasted in. That is what makes this a PORT rather
//! than a plausible reimplementation: if the Rust encoder and the Go encoder ever
//! disagree by one byte, this fails.

