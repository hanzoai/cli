#[test]
fn a_truncated_frame_is_an_error_not_a_panic() {
    // Every length in the frame is attacker-influenced on a shared socket, so
    // the decoder must refuse rather than index out of bounds.
    let mut f = vec![0u8; 64];
    f[0..4].copy_from_slice(MAGIC);
    f[4..6].copy_from_slice(&VERSION.to_le_bytes());
    f[6..8].copy_from_slice(&(FRAME_RESPONSE << 8).to_le_bytes());
    f[8..12].copy_from_slice(&(HEADER as u32).to_le_bytes());
    let size = f.len() as u32;
    f[12..16].copy_from_slice(&size.to_le_bytes());
    // Body slot points far past the end.
    let slot = HEADER + RESP_BODY;
    f[slot..slot + 4].copy_from_slice(&9999u32.to_le_bytes());
    f[slot + 4..slot + 8].copy_from_slice(&9999u32.to_le_bytes());
    assert!(decode_response(&f).is_err());
}

#[test]
fn a_wrong_magic_is_refused() {
    let f = vec![0u8; HEADER + SLOTS];
    assert!(decode_response(&f).is_err());
}
